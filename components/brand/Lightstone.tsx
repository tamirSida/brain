import { cn } from "@/lib/cn";

/**
 * Lightstone's identity, inlined.
 *
 * Inlined rather than loaded through <Image> for one reason: `currentColor`.
 * An external SVG is a separate document and cannot see the page's colour, so
 * a file-based logo has to ship once per theme. Inline, the mark follows the
 * surrounding text and the thinking state can be driven from CSS — which makes
 * the loading indicator a property of the logo rather than a second thing
 * parked beside it.
 *
 * Geometry is traced from the wordmark published on lightstonegroup.com; the
 * red is sampled from it (#D01E3B). The same ten glyph paths serve both marks,
 * the first of which — the L — is the mark on its own.
 */

/**
 * The L, centred in a square with an arc that orbits it while thinking.
 *
 * The arc carries the motion so the letterform never rotates. A spinning L
 * reads as a broken image rather than as a busy one, and a wordmark that turns
 * upside down stops being a wordmark — the same reason logos are excluded from
 * icon mirroring in RTL. The ring is the only thing that moves.
 */
export function LightstoneMark({ className }: { className?: string }) {
  return (
    <svg viewBox="0 0 100 100" className={cn("brand-mark", className)} fill="currentColor" aria-hidden>
      {/* Drawn before the letter so the letter always sits on top of it. */}
      <circle className="mark-ring" cx="50" cy="50" r="44" fill="none" stroke="#D01E3B" strokeWidth="4" strokeLinecap="round" />
      <g className="mark-glyph" transform="translate(29.98,78.22) scale(0.013033,-0.013033)" stroke="none">
        <path d="M0 2165 l0 -1995 1233 0 1232 0 27 25 27 25 82 102 83 103 15 16 16
17 15 18 15 19 34 45 35 45 35 40 36 41 35 43 35 43 58 70 59 69 -6 14 -5 15
-1088 2 -1088 3 -3 1618 -2 1617 -440 0 -440 0 0 -1995z" />
      </g>
    </svg>
  );
}

